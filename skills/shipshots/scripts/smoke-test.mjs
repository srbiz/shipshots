#!/usr/bin/env node
// ShipShots setup smoke test — verifies a running ShipShots server end to end.
//
//   node scripts/smoke-test.mjs                      # uses SHIPSHOTS_URL (default http://127.0.0.1:3000)
//   SHIPSHOTS_KEY=ss_live_... node scripts/smoke-test.mjs
//
// Without SHIPSHOTS_KEY it signs up a throwaway account, creates a temporary project,
// exercises upload → screenshot → PNG → Fastlane ZIP → MP4 rendering, prints a PASS/FAIL
// summary, and deletes the test project. Exits non-zero on failure.
import { randomUUID } from "node:crypto";
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";

const BASE = (process.env.SHIPSHOTS_URL ?? "http://127.0.0.1:3000").replace(/\/$/, "");
const API = `${BASE}/api/v1`;
const TMP = await fs.mkdtemp(path.join(os.tmpdir(), "shipshots-smoke-"));

const results = [];
let key = process.env.SHIPSHOTS_KEY ?? null;
let cookie = null;
let projectId = null;

async function call(label, method, p, { body, raw = false, auth = true } = {}) {
  const headers = {};
  if (auth && key) headers.authorization = `Bearer ${key}`;
  if (cookie) {
    headers.cookie = cookie;
    headers["x-requested-with"] = "shipshots"; // required for session-authenticated writes
  }
  if (body !== undefined) headers["content-type"] = "application/json";
  const res = await fetch(`${API}${p}`, { method, headers, body: body !== undefined ? JSON.stringify(body) : undefined });
  if (!res.ok) {
    const text = (await res.text()).slice(0, 300);
    throw new Error(`${label}: HTTP ${res.status} ${text}`);
  }
  if (raw) return Buffer.from(await res.arrayBuffer());
  return res.json();
}

function check(name, ok, detail = "") {
  results.push({ name, ok, detail });
  console.log(`${ok ? "PASS" : "FAIL"}  ${name}${detail ? ` — ${detail}` : ""}`);
}

async function step(name, fn) {
  try {
    const detail = await fn();
    check(name, true, detail);
    return true;
  } catch (e) {
    check(name, false, e instanceof Error ? e.message : String(e));
    return false;
  }
}

try {
  // 1. health
  const healthy = await step("server reachable (/api/health)", async () => {
    const r = await fetch(`${BASE}/api/health`);
    const j = await r.json();
    if (!r.ok || !j.ok) throw new Error(`health=${JSON.stringify(j)}`);
    return "postgres ok";
  });
  if (!healthy) {
    console.error(`\nServer not reachable at ${BASE}. Start ShipShots first (see SKILL.md setup).`);
    process.exit(1);
  }

  // 2. catalog
  await step("public catalog", async () => {
    const c = await call("catalog", "GET", "/catalog", { auth: false });
    if (!c.sizes?.length || !c.layouts?.length) throw new Error("catalog missing sizes/layouts");
    return `${c.sizes.length} sizes, ${c.layouts.length} layouts`;
  });

  // 3. credentials
  await step("authentication", async () => {
    if (key) return "using SHIPSHOTS_KEY";
    const email = `smoke-${randomUUID().slice(0, 8)}@shipshots.test`;
    const res = await fetch(`${API}/auth/signup`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ name: "Smoke Test", email, password: `smoke-${randomUUID()}` }),
    });
    if (!res.ok) throw new Error(`signup HTTP ${res.status}`);
    const setCookie = res.headers.getSetCookie?.() ?? [];
    cookie = setCookie.map((c) => c.split(";")[0]).join("; ");
    if (!cookie) throw new Error("no session cookie");
    const k = await call("create key", "POST", "/keys", { body: { name: `smoke-${Date.now()}` } });
    if (!k.token) throw new Error("no key token returned");
    key = k.token;
    cookie = null; // subsequent calls use the bearer key
    return "temp account + API key created";
  });

  // 4. project + screenshot
  let shotId = null;
  await step("project + screenshot", async () => {
    const p = await call("create project", "POST", "/projects", { body: { name: `Smoke ${Date.now()}`, platforms: "both", starter: true } });
    projectId = p.id;
    const detail = await call("project", "GET", `/projects/${projectId}`);
    if (!detail.screenshots?.length) throw new Error("no starter screenshots");
    shotId = detail.screenshots[0].id;
    await call("patch headline", "PATCH", `/screenshots/${shotId}`, { body: { headline: "Smoke *test* shot", subheadline: "generated by smoke-test.mjs" } });
    return `project ${projectId}, shot ${shotId}`;
  });

  // 5. single PNG render
  await step("single PNG render", async () => {
    const png = await call("render png", "GET", `/screenshots/${shotId}/render?size=iphone-69&download=1`, { raw: true });
    if (png.length < 1000 || png.readUInt32BE(0) !== 0x89504e47) throw new Error("not a PNG");
    await fs.writeFile(path.join(TMP, "shot.png"), png);
    return `${png.length} bytes → ${path.join(TMP, "shot.png")}`;
  });

  // 6. Fastlane ZIP
  await step("fastlane ZIP render", async () => {
    const zip = await call("render zip", "POST", `/projects/${projectId}/render`, { body: { layout: "fastlane", sizes: ["iphone-69", "android-phone"] }, raw: true });
    if (zip.length < 1000 || zip.readUInt32BE(0) !== 0x504b0304) throw new Error("not a ZIP");
    await fs.writeFile(path.join(TMP, "store.zip"), zip);
    return `${zip.length} bytes → ${path.join(TMP, "store.zip")}`;
  });

  // 7. preview video (optional — needs ffmpeg on the server)
  await step("MP4 preview video render", async () => {
    const v = await call("create video", "POST", `/projects/${projectId}/videos`, { body: {} });
    const mp4 = await call("render mp4", "POST", `/videos/${v.id}/render`, { body: { save: false }, raw: true });
    if (mp4.length < 1000 || mp4.subarray(4, 8).toString() !== "ftyp") throw new Error("not an MP4");
    await fs.writeFile(path.join(TMP, "preview.mp4"), mp4);
    return `${mp4.length} bytes → ${path.join(TMP, "preview.mp4")}`;
  });

  // 8. cleanup
  if (projectId && !process.env.SHIPSHOTS_KEY) {
    try {
      await call("cleanup", "DELETE", `/projects/${projectId}`);
      console.log("INFO  test project deleted");
    } catch (e) {
      console.log(`WARN  could not delete test project ${projectId}: ${e.message}`);
    }
  }
} finally {
  // Keep artifacts on success so the user can inspect them; clean up on failure.
  if (results.some((r) => !r.ok)) await fs.rm(TMP, { recursive: true, force: true }).catch(() => {});
}

const failed = results.filter((r) => !r.ok);
console.log(`\n${results.length - failed.length}/${results.length} checks passed${failed.length ? `, ${failed.length} FAILED` : ""}`);
if (!failed.length) console.log(`Artifacts kept in: ${TMP}`);
process.exit(failed.length ? 1 : 0);
